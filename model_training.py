"""
Train supervised machine-learning models for historical forward drawdown risk.

Run after:
    python ml_dataset.py

This upgraded version adds the main improvements requested after the first ML run:

1. Top-decile risk analysis:
   Instead of only asking whether a model crosses a 0.50 probability threshold,
   we ask a more useful risk-monitoring question: what happened historically when
   a model placed an observation in its highest-risk 10% of scores?

2. Tuned thresholds:
   Rare-event problems should not blindly use 0.50 as the alert threshold. A 20%
   estimated crash-risk can be historically high when the base event rate is only
   5%-12%. We therefore tune each model's warning threshold on the validation
   period and apply that same threshold to the later test period.

3. Segment-specific models:
   A 30% drawdown means different things for SPY, NVDA, PLTR, and BTC. The code
   trains a global model and, where enough data exists, separate models for:
       - broad_index_etf
       - mega_cap_ai_tech
       - speculative_high_vol

4. Calibration tables:
   The code saves decile-based reliability tables so the dashboard can show
   whether high model scores historically corresponded to higher actual event
   rates. This does not make the model prophetic; it simply makes the probability
   scale more honest.

Outputs:
    models/*.pkl
    models/ml_preprocessor.pkl
    data/processed/ml_model_results.parquet
    data/processed/ml_test_predictions.parquet
    data/processed/ml_feature_importance.parquet
    data/processed/ml_thresholds.parquet
    data/processed/ml_top_decile_analysis.parquet
    data/processed/ml_calibration_table.parquet

Research framing:
    These models estimate whether current conditions resemble historical setups
    that were followed by a major forward drawdown. They do not predict exact
    tops, bottoms, or dates.
"""
