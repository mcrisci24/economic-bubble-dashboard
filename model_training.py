def slugify(value: str) -> str:
    """Make a safe filename slug from a model or segment name."""
    return re.sub(r"[^a-z0-9]+", "_", value.lower()).strip("_")


def infer_asset_segment(ticker: str) -> str:
    """Assign each ticker to the most relevant ML segment.

    The ordering matters. Some ETFs such as ARKK are broad baskets but behave
    like high-volatility growth assets; however, for this first version we place
    ETFs in broad_index_etf so the segment remains stable. Individual speculative
    names and crypto go to speculative_high_vol. Mega-cap AI and legacy tech go
    to mega_cap_ai_tech.
    """
    for segment, tickers in SEGMENT_TICKERS.items():
        if ticker in tickers:
            return segment
    if ticker.endswith("-USD"):
        return "speculative_high_vol"
    if ticker.startswith("^"):
        return "broad_index_etf"
    return "other_single_name"


